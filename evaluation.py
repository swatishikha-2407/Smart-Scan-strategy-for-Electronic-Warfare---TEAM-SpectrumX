"""
Evaluation logic for individual schedulers.

This module takes simulation records generated by a scheduler
and calculates the required performance metrics.
"""

from typing import Any, Dict, List

from .metrics import (
    calculate_average_detection_delay,
    calculate_average_reward,
    calculate_coverage,
    calculate_detection_interception_rate,
    calculate_detection_rate,
    calculate_false_alarm_count,
    calculate_false_alarm_rate,
    calculate_hit_count,
    calculate_miss_count,
    calculate_total_scans,
)


def evaluate_scheduler(
    scenario: str,
    num_bands: int,
    time_steps: int,
    seed: int,
    scheduler_type: str,
    scan_records: List[Dict[str, Any]],
    transmission_events: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """
    Evaluate one scheduler against one simulated scenario.

    Parameters
    ----------
    scenario : str
        Name of the simulated scenario.

    num_bands : int
        Number of simulated frequency bands.

    time_steps : int
        Number of simulation time steps.

    seed : int
        Random seed used for the experiment.

    scheduler_type : str
        Scheduler name, for example:
            "sequential"
            "smart"

    scan_records : list of dict
        Records generated by the scheduler.

        Each scan record should contain:

            {
                "time_step": int,
                "band": int,
                "active": bool,
                "detected": bool,
                "reward": float
            }

    transmission_events : list of dict
        Simulated transmission events.

        Each event should contain:

            {
                "event_id": int,
                "band": int,
                "start_time": int,
                "detected": bool,
                "detection_time": int | None
            }

    Returns
    -------
    dict
        Structured metrics for the scheduler.
    """

    # ---------------------------------------------------------
    # Basic counts
    # ---------------------------------------------------------

    total_transmission_events = len(transmission_events)

    detected_transmission_events = sum(
        1
        for event in transmission_events
        if event.get("detected", False)
    )

    # ---------------------------------------------------------
    # Detection rate
    # ---------------------------------------------------------

    detection_rate = calculate_detection_rate(
        successful_detections=detected_transmission_events,
        actual_transmission_opportunities=total_transmission_events,
    )

    # ---------------------------------------------------------
    # Hit and miss counts
    # ---------------------------------------------------------

    hit_count = calculate_hit_count(
        detected_transmission_events
    )

    miss_count = calculate_miss_count(
        total_transmission_events=total_transmission_events,
        detected_transmission_events=detected_transmission_events,
    )

    # ---------------------------------------------------------
    # False alarms
    # ---------------------------------------------------------

    false_alarm_records = [
        record
        for record in scan_records
        if (
            record.get("active", False) is False
            and record.get("detected", False) is True
        )
    ]

    false_alarm_count = calculate_false_alarm_count(
        false_alarm_records
    )

    inactive_band_scans = sum(
        1
        for record in scan_records
        if record.get("active", False) is False
    )

    false_alarm_rate = calculate_false_alarm_rate(
        false_alarm_count=false_alarm_count,
        inactive_band_scans=inactive_band_scans,
    )

    # ---------------------------------------------------------
    # Detection delays
    # ---------------------------------------------------------

    detection_delays = []

    for event in transmission_events:

        if (
            event.get("detected", False)
            and event.get("detection_time") is not None
        ):
            delay = (
                event["detection_time"]
                - event["start_time"]
            )

            # Delay should never be negative.
            delay = max(0, delay)

            detection_delays.append(delay)

    average_detection_delay = calculate_average_detection_delay(
        detection_delays
    )

    # ---------------------------------------------------------
    # Detection / interception rate
    # ---------------------------------------------------------

    detection_interception_rate = (
        calculate_detection_interception_rate(
            detected_transmission_events=detected_transmission_events,
            total_transmission_events=total_transmission_events,
        )
    )

    # ---------------------------------------------------------
    # Reward
    # ---------------------------------------------------------

    rewards = [
        record.get("reward", 0.0)
        for record in scan_records
    ]

    average_reward = calculate_average_reward(rewards)

    # ---------------------------------------------------------
    # Number of scans
    # ---------------------------------------------------------

    total_scans = calculate_total_scans(scan_records)

    # ---------------------------------------------------------
    # Coverage
    # ---------------------------------------------------------

    scanned_bands = [
        record.get("band")
        for record in scan_records
        if record.get("band") is not None
    ]

    coverage = calculate_coverage(
        scanned_bands=scanned_bands,
        total_bands=num_bands,
    )

    # ---------------------------------------------------------
    # Return structured result
    # ---------------------------------------------------------

    return {
        "scenario": scenario,
        "num_bands": num_bands,
        "time_steps": time_steps,
        "seed": seed,
        "scheduler": scheduler_type,

        "detection_rate": detection_rate,

        "false_alarm_rate": false_alarm_rate,

        "average_detection_delay": average_detection_delay,

        "detection_interception_rate": (
            detection_interception_rate
        ),

        "average_reward": average_reward,

        "total_scans": total_scans,

        "hit_count": hit_count,

        "miss_count": miss_count,

        "false_alarm_count": false_alarm_count,

        "coverage": coverage,

        "total_transmission_events": (
            total_transmission_events
        ),

        "detected_transmission_events": (
            detected_transmission_events
        ),
    }
